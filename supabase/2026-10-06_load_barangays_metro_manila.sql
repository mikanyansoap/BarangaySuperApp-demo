-- Fill whatever columns your barangays table has (e.g. city_municipality, province, region).
do $$
declare
  col_city   text;
  col_prov   text;
  col_region text;
  cols       text := 'psgc_code, name';
  sel        text := 'public.to_modern_psgc(l.code9), l.name';
  sets       text := '';
  r          record;
begin
  select column_name into col_city from information_schema.columns
   where table_schema = 'public' and table_name = 'barangays'
     and column_name in ('city_municipality', 'city', 'municipality', 'city_name')
   order by array_position(array['city_municipality', 'city', 'municipality', 'city_name'], column_name::text)
   limit 1;
  select column_name into col_prov from information_schema.columns
   where table_schema = 'public' and table_name = 'barangays'
     and column_name in ('province', 'province_name') limit 1;
  select column_name into col_region from information_schema.columns
   where table_schema = 'public' and table_name = 'barangays'
     and column_name in ('region', 'region_name') and data_type in ('text', 'character varying') limit 1;

  if col_city is null then
    alter table public.barangays add column city_municipality text;
    col_city := 'city_municipality';
  end if;

  cols := cols || ', ' || quote_ident(col_city);
  sel  := sel  || ', l.city';
  sets := format('%1$I = coalesce(b.%1$I, l.city)', col_city);
  if col_prov is not null then
    cols := cols || ', ' || quote_ident(col_prov);
    sel  := sel  || ', l.province';
    sets := sets || format(', %1$I = coalesce(b.%1$I, l.province)', col_prov);
  end if;
  if col_region is not null then
    cols := cols || ', ' || quote_ident(col_region);
    sel  := sel  || ', l.region';
    sets := sets || format(', %1$I = coalesce(b.%1$I, l.region)', col_region);
  end if;

  -- any other required text column without a default gets an empty string instead of failing
  for r in
    select column_name from information_schema.columns
     where table_schema = 'public' and table_name = 'barangays'
       and is_nullable = 'NO' and column_default is null and is_generated = 'NEVER'
       and data_type in ('text', 'character varying')
       and column_name not in ('psgc_code', 'name', col_city, coalesce(col_prov, '-'), coalesce(col_region, '-'))
  loop
    cols := cols || ', ' || quote_ident(r.column_name);
    sel  := sel  || ', ''''';
  end loop;

  -- fill missing city / province / region on rows that already exist
  execute format('update public.barangays b set %s from _brgy_load l
                   where b.psgc_code = public.to_modern_psgc(l.code9)', sets);

  -- add the missing barangays
  execute format('insert into public.barangays (%s) select %s from _brgy_load l
                   where not exists (select 1 from public.barangays b
                                      where b.psgc_code = public.to_modern_psgc(l.code9))', cols, sel);
end $$;

commit;

